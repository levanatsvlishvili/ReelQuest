/**
 * Format raw revenue numbers into attractive currency strings:
 * e.g. 839030630 -> "$839,030,630"
 */
export function formatFullRevenue(num) {
  if (typeof num !== 'number' || isNaN(num)) return '$0';
  return '$' + num.toLocaleString('en-US');
}

/**
 * Format into abbreviated display (e.g. "$839.0M" or "$2.92B")
 */
export function formatShortRevenue(num) {
  if (typeof num !== 'number' || isNaN(num)) return '$0';
  if (num >= 1000000000) {
    return '$' + (num / 1000000000).toFixed(2) + 'B';
  }
  if (num >= 1000000) {
    return '$' + (num / 1000000).toFixed(1) + 'M';
  }
  return '$' + num.toLocaleString('en-US');
}

/**
 * Deterministically generates the 5 matchups for the Daily 5-Round Challenge
 * for any given YYYY-MM-DD date string.
 */
export function getDailyBoxOfficeMatchups(dateStr) {
  if (!dateStr || dateStr === 'Today') {
    dateStr = new Date().toISOString().slice(0, 10);
  }
  let seed = 0;
  for (let i = 0; i < dateStr.length; i++) {
    seed = (seed << 5) - seed + dateStr.charCodeAt(i);
    seed |= 0;
  }
  seed = Math.abs(seed);

  const total = BOX_OFFICE_MOVIES.length;
  const pairs = [];
  const used = new Set();

  for (let round = 0; round < 5; round++) {
    let idxA = (seed + round * 17 + 3) % total;
    while (used.has(idxA)) idxA = (idxA + 1) % total;
    used.add(idxA);

    let idxB = (seed + round * 31 + 19) % total;
    while (used.has(idxB) || idxB === idxA) idxB = (idxB + 1) % total;
    used.add(idxB);

    pairs.push({
      round: round + 1,
      movieA: BOX_OFFICE_MOVIES[idxA],
      movieB: BOX_OFFICE_MOVIES[idxB]
    });
  }

  return pairs;
}

/**
 * Picks a random contender distinct from the current movie and used list.
 */
export function getRandomContender(excludeIds = []) {
  const excludeSet = new Set(excludeIds);
  const candidates = BOX_OFFICE_MOVIES.filter(m => !excludeSet.has(m.id));
  if (candidates.length === 0) {
    return BOX_OFFICE_MOVIES[Math.floor(Math.random() * BOX_OFFICE_MOVIES.length)];
  }
  return candidates[Math.floor(Math.random() * candidates.length)];
}
