export function getTimecodeMovieForDate(dateStr) {
  if (!dateStr || dateStr === 'Today') {
    dateStr = new Date().toISOString().slice(0, 10);
  }
  let hash = 2166136261;
  const salted = 'timecode:' + dateStr;
  for (let i = 0; i < salted.length; i++) {
    hash ^= salted.charCodeAt(i);
    hash = Math.imul(hash, 16777619);
  }
  const positiveIndex = Math.abs(hash) % TIMECODE_MOVIES.length;
  return TIMECODE_MOVIES[positiveIndex];
}
